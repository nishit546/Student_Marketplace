// Helper to look up a product by id or _id
export function getProductById(id: string): Product | undefined {
  return SAMPLE_PRODUCTS.find((p) => p.id === id || p._id === id);
}

// Helper to find similar products by category
export function getSimilarProducts(currentProductId: string, category: string, limit = 4): Product[] {
  return SAMPLE_PRODUCTS.filter(
    (p) => (p.id !== currentProductId && p._id !== currentProductId) &&
      (p.category.toLowerCase().includes(category.toLowerCase()) || category.toLowerCase().includes(p.category.toLowerCase()))
  ).slice(0, limit);
}
